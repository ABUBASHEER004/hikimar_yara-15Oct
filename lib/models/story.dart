class Story {
  final String id;
  final String title;
  final String image;
  final String author;
  final String duration;
  final String category;
  final String description;
  final String content;
  final String audio;

  const Story({
    required this.id,
    required this.title,
    required this.image,
    required this.author,
    required this.duration,
    required this.category,
    required this.description,
    required this.content,
    required this.audio,
  });
}